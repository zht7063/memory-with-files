// The Pi extension `mwf install --harness pi` writes: <PI_CODING_AGENT_DIR or ~/.pi/agent>/extensions/mwf.js.
//
// Pi has no hooks file, so hooks (and the `/mwf` command) live in a small generated extension. It is a
// THIN SHELL: every event runs `<node> <mwf.js> hook <event> --host pi` (the same supervised command
// Codex and Claude Code run: stdin JSON, one JSON line out, a hard time budget), so a hook can never
// hang or crash Pi and there is one code path (src/hooks) for every host. The extension has no
// dependencies besides node:child_process and does no memory work itself.
//
// What it does (event names and shapes verified against @earendil-works/pi-coding-agent 1.4.0):
//   session_start        records the session (reason -> the handler's `source`); injects nothing
//   input                remembers the raw line, so `/mwf…` and `/skill:mwf…` lines skip recall
//   before_agent_start   first run of a session: `session-start` overview; every run: `prompt` recall;
//                        returned as ONE custom message (display:false, so it is kept in the session like
//                        Codex's and Claude's additionalContext). Never touches the system prompt.
//   agent_before_settle  `stop`: at most ONE continuation per user prompt and session, only when the run
//                        completed; the handoff/save request is a custom message entry + continue:true
//   /mwf                 init|status|recall|save|handoff|tidy (see SHORTCUTS)
// Anything that goes wrong (spawn failure, timeout, bad output) injects nothing and never continues.
//
// The file starts with `// mwf-managed:<version>:<sha256 of everything after this line>`: install and
// uninstall change only a file whose hash still matches. Every path baked into it goes through
// JSON.stringify (so quotes, backslashes, `${}`, newlines and the like in a path cannot become code).
import { renderForHost, SHORTCUTS } from '../skills/index.ts';
import { sha256Hex } from './safe-write.ts';

export const EXTENSION_NAME = 'mwf.js';

const MARKER = /^\/\/ mwf-managed:([^:\s]+):([0-9a-f]{64})\n/;

/** The hook time budget the extension gives `mwf hook` (the supervisor itself answers within 4 s). */
export const EXTENSION_HOOK_MS = 5_000;
/** The budget for `/mwf status` and `/mwf recall`. */
export const EXTENSION_COMMAND_MS = 15_000;

export interface ExtensionSpec {
  node: string;
  mwfJs: string;
  version: string;
}

/** What `/mwf <name>` does: the text for the agent (rendered for Pi) or, for status/recall, a CLI call. */
function commandTable(): Record<string, { usage: string; instructions: string; cli?: string }> {
  const table: Record<string, { usage: string; instructions: string; cli?: string }> = {};
  for (const s of SHORTCUTS) {
    table[s.name] = {
      usage: s.usage,
      instructions: renderForHost(s.instructions, 'pi'),
      ...(s.name === 'status' || s.name === 'recall' ? { cli: s.name } : {}),
    };
  }
  return table;
}

// NOTE for editors: no backquote and no dollar-brace may appear below (this is a TS template literal
// whose JS has to stay literal); baked values arrive only through the four __PLACEHOLDERS__.
const BODY = `// Generated by "mwf install --harness pi". Do not edit: "mwf install" rewrites this file and
// "mwf uninstall" removes it, but only while it is exactly what mwf wrote (see the hash above).
// It runs inside Pi with Pi's permissions; it only starts the mwf program named below.
import { spawn } from "node:child_process";

const NODE = __NODE__;
const MWF_JS = __MWF_JS__;
const HOOK_MS = __HOOK_MS__;
const COMMAND_MS = __COMMAND_MS__;
const COMMANDS = __COMMANDS__;
const MAX_OUT = 262144;
const NAMES = { "session-start": "SessionStart", prompt: "UserPromptSubmit", stop: "Stop" };
const SOURCES = { startup: "startup", reload: "resume", new: "clear", resume: "resume", fork: "fork" };
const MAX_SESSIONS = 64;

// Runs node MWF_JS args; resolves { code, out } or null (could not start, timed out, too much output).
function run(args, input, ms) {
  return new Promise((resolve) => {
    let done = false;
    let out = "";
    let child;
    const finish = (value) => {
      if (done) return;
      done = true;
      clearTimeout(timer);
      try {
        if (child && child.exitCode === null && child.signalCode === null) child.kill("SIGKILL");
      } catch {}
      resolve(value);
    };
    const timer = setTimeout(() => finish(null), ms);
    try {
      child = spawn(NODE, [MWF_JS].concat(args), { stdio: ["pipe", "pipe", "ignore"], windowsHide: true });
    } catch {
      return finish(null);
    }
    child.on("error", () => finish(null));
    child.stdin.on("error", () => {});
    child.stdout.on("data", (chunk) => {
      out += chunk.toString("utf8");
      if (out.length > MAX_OUT) finish(null);
    });
    child.on("close", (code) => finish({ code, out }));
    child.stdin.end(input || "");
  });
}

// One hook event; the parsed JSON object it printed, or null.
async function hook(event, payload) {
  const input = JSON.stringify(Object.assign({ hook_event_name: NAMES[event] }, payload));
  const r = await run(["hook", event, "--host", "pi"], input, HOOK_MS);
  if (!r || r.code !== 0) return null;
  try {
    const value = JSON.parse(r.out.split("\\n", 1)[0]);
    return value && typeof value === "object" && !Array.isArray(value) ? value : null;
  } catch {
    return null;
  }
}

const contextOf = (r) =>
  r && r.hookSpecificOutput && typeof r.hookSpecificOutput.additionalContext === "string"
    ? r.hookSpecificOutput.additionalContext
    : "";

function sessionIdOf(ctx) {
  try {
    const id = ctx.sessionManager.getSessionId();
    return typeof id === "string" && id ? id : null;
  } catch {
    return null;
  }
}

function notify(ctx, text, level) {
  try {
    if (ctx.hasUI && text) ctx.ui.notify(text, level || "info");
  } catch {}
}

export default function (pi) {
  // Per session: the source still to be announced to SessionStart, the user-prompt counter, and the
  // prompt the one allowed continuation was already used for (the counter is per session).
  const sessions = new Map();
  let raw = null; // the raw line of the input that starts the next run
  let skipRecall = false; // set while this extension itself sends one of its /mwf instructions

  const stateOf = (id, create) => {
    let s = sessions.get(id);
    if (!s && create) {
      s = { source: "startup", seq: 0, promptId: null, continuedFor: null };
      sessions.set(id, s);
      if (sessions.size > MAX_SESSIONS) sessions.delete(sessions.keys().next().value);
    }
    return s;
  };

  pi.on("session_start", (event, ctx) => {
    try {
      const id = sessionIdOf(ctx);
      if (!id) return;
      const s = stateOf(id, true);
      s.source = SOURCES[event && event.reason] || "startup";
      s.continuedFor = null;
    } catch {}
  });

  pi.on("input", (event) => {
    try {
      raw = event && typeof event.text === "string" ? event.text : null;
    } catch {}
    return { action: "continue" };
  });

  pi.on("before_agent_start", async (event, ctx) => {
    try {
      if (event && event.messageType === "custom") return undefined;
      const line = skipRecall ? "/mwf" : raw !== null ? raw : event && event.prompt;
      raw = null;
      skipRecall = false;
      const id = sessionIdOf(ctx);
      const base = { cwd: ctx.cwd };
      let promptId;
      let start = null;
      if (id) {
        const s = stateOf(id, true);
        s.seq += 1;
        s.promptId = id + ":" + s.seq;
        promptId = s.promptId;
        base.session_id = id;
        start = s.source;
        s.source = null;
      }
      const parts = [];
      const notices = [];
      if (start) {
        const r = await hook("session-start", Object.assign({ source: start }, base));
        if (r && r.systemMessage) notices.push(r.systemMessage);
        if (contextOf(r)) parts.push(contextOf(r));
      }
      const payload = Object.assign({ prompt: typeof line === "string" ? line : "" }, base);
      if (promptId) payload.prompt_id = promptId;
      const r = await hook("prompt", payload);
      if (r && r.systemMessage) notices.push(r.systemMessage);
      if (contextOf(r)) parts.push(contextOf(r));
      for (const n of notices) notify(ctx, n, "info");
      if (parts.length === 0) return undefined;
      return { message: { customType: "mwf", content: parts.join("\\n\\n"), display: false } };
    } catch {
      return undefined;
    }
  });

  pi.on("agent_before_settle", async (event, ctx) => {
    try {
      if (!event || event.outcome !== "completed" || event.continue === true) return undefined;
      if (event.context && event.context.canContinue === false) return undefined;
      const id = sessionIdOf(ctx);
      if (!id) return undefined;
      const s = stateOf(id, false);
      if (!s || !s.promptId || s.continuedFor === s.promptId) return undefined;
      const promptId = s.promptId;
      s.continuedFor = promptId; // claimed before asking: a slow or failing hook still counts as the one try
      const r = await hook("stop", {
        cwd: ctx.cwd,
        session_id: id,
        prompt_id: promptId,
        stop_hook_active: false,
      });
      if (!r || r.decision !== "block" || typeof r.reason !== "string" || !r.reason) return undefined;
      const entries = Array.isArray(event.entries) ? event.entries.slice() : [];
      entries.push({ type: "custom_message", customType: "mwf", content: r.reason, display: false });
      return { entries, continue: true };
    } catch {
      return undefined;
    }
  });

  const usage = () =>
    Object.keys(COMMANDS)
      .map((name) => COMMANDS[name].usage)
      .join("\\n");

  pi.registerCommand("mwf", {
    description: "mwf project memory: " + Object.keys(COMMANDS).join(", "),
    getArgumentCompletions: (prefix) => {
      const p = String(prefix || "").trim();
      if (/\\s/.test(p)) return null;
      const items = Object.keys(COMMANDS)
        .filter((name) => name.startsWith(p))
        .map((name) => ({ value: name, label: name, description: COMMANDS[name].usage }));
      return items.length > 0 ? items : null;
    },
    handler: async (args, ctx) => {
      try {
        const text = String(args || "").trim();
        const space = text.search(/\\s/);
        const name = space < 0 ? text : text.slice(0, space);
        const rest = space < 0 ? "" : text.slice(space).trim();
        const command = Object.prototype.hasOwnProperty.call(COMMANDS, name) ? COMMANDS[name] : null;
        if (!command) {
          notify(ctx, (name ? 'Unknown /mwf command "' + name + '". ' : "") + "Usage:\\n" + usage(), name ? "warning" : "info");
          return;
        }
        const addendum = rest ? "\\n\\n" + (name === "recall" ? "Query: " : "Text: ") + rest : "";
        if (command.cli && ctx.hasUI) {
          // Shown to you only (a transient notification): not written to the session, never sent to the model.
          const argv = [command.cli, "--cwd", ctx.cwd];
          if (command.cli === "recall" && rest) argv.splice(1, 0, rest);
          if (command.cli === "recall") argv.push("--max-chars", "2000");
          const r = await run(argv, "", COMMAND_MS);
          const out = r ? r.out.trim() : "";
          notify(ctx, out || "mwf " + command.cli + " did not answer in time.", r && r.code === 0 ? "info" : "warning");
          return;
        }
        // No UI to show it in (or an agent command): the agent does it through the MCP tools.
        skipRecall = true;
        await pi.sendUserMessage(command.instructions + addendum);
      } catch {
        skipRecall = false;
      }
    },
  });
}
`;

/** The extension file for these paths: the marker line, then the body with the paths baked in. */
export function renderExtension(spec: ExtensionSpec): string {
  // one pass over the template: a baked value is never scanned again for placeholders
  const values: Record<string, string> = {
    NODE: JSON.stringify(spec.node),
    MWF_JS: JSON.stringify(spec.mwfJs),
    HOOK_MS: String(EXTENSION_HOOK_MS),
    COMMAND_MS: String(EXTENSION_COMMAND_MS),
    COMMANDS: JSON.stringify(commandTable()),
  };
  const body = BODY.replace(
    /__(NODE|MWF_JS|HOOK_MS|COMMAND_MS|COMMANDS)__/g,
    (_m, key: string) => values[key]!,
  );
  return `// mwf-managed:${spec.version}:${sha256Hex(body)}\n${body}`;
}

export type ExtensionState = { kind: 'none' } | { kind: 'intact' | 'modified'; version: string };

/** Is this file text what `renderExtension` wrote (intact), edited since (modified) or not ours (none)? */
export function classifyExtension(text: string): ExtensionState {
  const m = MARKER.exec(text);
  if (!m) return { kind: 'none' };
  const body = text.slice(m[0].length);
  return { kind: sha256Hex(body) === m[2] ? 'intact' : 'modified', version: m[1]! };
}
